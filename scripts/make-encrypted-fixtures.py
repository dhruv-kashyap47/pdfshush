"""Builds the encrypted fixtures the Unlock tests and E2E need.

Dev-time only (pypdf is not a repo dependency). `test/encryptedFixtures.ts` is
generated from the same bytes because pdf-core compiles with `"types": []` and
cannot read files from a test.

    python scripts/make-encrypted-fixtures.py            # PDFs + base64 module
    python scripts/make-encrypted-fixtures.py --module-only   # module from the
                                                              # committed PDFs
"""

import argparse
import base64
import os
import textwrap

from pypdf import PdfReader, PdfWriter
from pypdf.generic import DecodedStreamObject, DictionaryObject, NameObject

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "packages", "pdf-core", "test", "fixtures")
MODULE = os.path.join(ROOT, "packages", "pdf-core", "test", "encryptedFixtures.ts")

AES = "encrypted-aes128.pdf"
OWNER = "encrypted-owner-only.pdf"


def build_source(path: str) -> None:
    writer = PdfWriter()
    page = writer.add_blank_page(width=595, height=842)

    font = DictionaryObject(
        {
            NameObject("/Type"): NameObject("/Font"),
            NameObject("/Subtype"): NameObject("/Type1"),
            NameObject("/BaseFont"): NameObject("/Helvetica"),
        }
    )
    font_ref = writer._add_object(font)
    page[NameObject("/Resources")] = DictionaryObject(
        {NameObject("/Font"): DictionaryObject({NameObject("/F1"): font_ref})}
    )

    content = DecodedStreamObject()
    content.set_data(b"BT /F1 18 Tf 48 780 Td (Locked page - PDFShush unlock test) Tj ET")
    page[NameObject("/Contents")] = writer._add_object(content)

    with open(path, "wb") as handle:
        writer.write(handle)


def encrypt(src: str, dst: str, user: str, owner: str) -> None:
    reader = PdfReader(src)
    writer = PdfWriter()
    for page in reader.pages:
        writer.add_page(page)
    writer.encrypt(user_password=user, owner_password=owner, algorithm="AES-128")
    with open(dst, "wb") as handle:
        writer.write(handle)


def base64_block(name: str, path: str, comment: str) -> str:
    value = base64.b64encode(open(path, "rb").read()).decode("ascii")
    lines = textwrap.wrap(value, 96)
    body = "\n".join(f"  '{line}' +" for line in lines[:-1])
    if body:
        body += "\n"
    body += f"  '{lines[-1]}';\n"
    return f"/** {comment} */\nexport const {name} =\n{body}\n"


def write_module() -> None:
    module = (
        "/**\n"
        " * Encrypted fixtures, base64-encoded.\n"
        " *\n"
        ' * pdf-core compiles with `"types": []`, so tests cannot import node:fs to\n'
        " * read the committed PDFs sitting next to this file. These are the same\n"
        " * bytes; E2E uploads the real files. Generated by\n"
        " * scripts/make-encrypted-fixtures.py -- edit that script, not this module.\n"
        " */\n\n"
        + base64_block(
            "ENCRYPTED_AES128_BASE64",
            os.path.join(OUT, AES),
            "One page, AES-128, user password shush123, owner password owner-secret.",
        )
        + base64_block(
            "ENCRYPTED_OWNER_ONLY_BASE64",
            os.path.join(OUT, OWNER),
            "One page, AES-128, empty user password; opens without being asked.",
        )
        + "const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';\n\n"
        "/**\n"
        " * Small dependency-free base64 decoder (the package has no Node types, and\n"
        " * `atob` is not in its lib). Padding and whitespace are ignored.\n"
        " */\n"
        "export function decodeBase64(value: string): Uint8Array {\n"
        "  const clean = value.replace(/[^A-Za-z0-9+/]/g, '');\n"
        "  const out = new Uint8Array(Math.floor((clean.length * 3) / 4));\n"
        "  let buffer = 0;\n"
        "  let bits = 0;\n"
        "  let index = 0;\n"
        "  for (const char of clean) {\n"
        "    const digit = ALPHABET.indexOf(char);\n"
        "    if (digit < 0) continue;\n"
        "    buffer = (buffer << 6) | digit;\n"
        "    bits += 6;\n"
        "    if (bits >= 8) {\n"
        "      bits -= 8;\n"
        "      out[index] = (buffer >> bits) & 0xff;\n"
        "      index += 1;\n"
        "    }\n"
        "  }\n"
        "  return out.subarray(0, index);\n"
        "}\n"
    )
    with open(MODULE, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(module)
    print("wrote", os.path.relpath(MODULE, ROOT))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--module-only",
        action="store_true",
        help="regenerate the base64 TS module from the committed PDFs",
    )
    args = parser.parse_args()

    os.makedirs(OUT, exist_ok=True)
    if not args.module_only:
        plain = os.path.join(OUT, ".plain.pdf")
        build_source(plain)
        encrypt(plain, os.path.join(OUT, AES), "shush123", "owner-secret")
        # Owner-only restrictions: opens without a password, permissions are limited.
        encrypt(plain, os.path.join(OUT, OWNER), "", "owner-secret")
        os.remove(plain)
        for name in (AES, OWNER):
            print(name, os.path.getsize(os.path.join(OUT, name)), "bytes")

    write_module()


if __name__ == "__main__":
    main()
