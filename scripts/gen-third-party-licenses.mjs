#!/usr/bin/env node
/**
 * Generates `THIRD_PARTY_LICENSES.deps.md`: the licence texts of every
 * production dependency, read from the packages that pnpm actually installed.
 *
 * Why a generator instead of a hand-written list: MIT, BSD and ISC all require
 * their copyright notice to travel with the distributed code, and a list of
 * package names is not that notice. Reading each package's own licence file
 * keeps the copyright lines authoritative and makes a dependency bump show up
 * as a reviewable diff.
 *
 * Dev-only packages (Playwright, axe-core, Vitest, TypeScript) are deliberately
 * excluded: they are not part of the deployed Worker or SPA. Their licences are
 * still checked by `pnpm licenses list`.
 *
 * Usage: `node scripts/gen-third-party-licenses.mjs` (wired to
 * `pnpm deps:licenses`). Run it after any dependency change and commit the
 * result.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'THIRD_PARTY_LICENSES.deps.md');
const PNPM = process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm';

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.|-|$)/i;
const SKIP_PACKAGE = /^@pdfshush\//;

function readLicenceText(directory) {
  let entries;
  try {
    entries = readdirSync(directory, { withFileTypes: true });
  } catch {
    return undefined;
  }
  const candidates = entries
    .filter((entry) => entry.isFile() && LICENSE_FILE.test(entry.name))
    .map((entry) => entry.name)
    .sort((a, b) => {
      // Prefer the plain licence over NOTICE/COPYING when both exist; NOTICE is
      // included separately by its own entry only if it is all there is.
      const rank = (name) => (/^licen[cs]e/i.test(name) ? 0 : /^copying/i.test(name) ? 1 : 2);
      return rank(a) - rank(b) || a.localeCompare(b);
    });

  for (const name of candidates) {
    const file = path.join(directory, name);
    try {
      const text = readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim();
      if (text.length > 0) return { file: name, text };
    } catch {
      // Unreadable candidate: keep looking.
    }
  }
  return undefined;
}

function inventory() {
  const raw = execFileSync(PNPM, ['-r', 'licenses', 'list', '--prod', '--json'], {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    shell: process.platform === 'win32',
  });
  const parsed = JSON.parse(raw);
  const packages = [];
  for (const [declared, entries] of Object.entries(parsed)) {
    for (const entry of entries) {
      if (SKIP_PACKAGE.test(entry.name)) continue;
      for (const [index, version] of entry.versions.entries()) {
        packages.push({
          name: entry.name,
          version,
          license: entry.license || declared,
          directory: entry.paths[index] ?? entry.paths[0],
        });
      }
    }
  }
  return packages.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function main() {
  const packages = inventory();
  const missing = [];
  const groups = new Map(); // license id -> Map(text -> {file, names:Set})

  for (const pkg of packages) {
    const found = pkg.directory ? readLicenceText(pkg.directory) : undefined;
    if (!found) {
      missing.push(pkg);
      continue;
    }
    let byText = groups.get(pkg.license);
    if (!byText) {
      byText = new Map();
      groups.set(pkg.license, byText);
    }
    let group = byText.get(found.text);
    if (!group) {
      group = { file: found.file, packages: [] };
      byText.set(found.text, group);
    }
    group.packages.push(`${pkg.name}@${pkg.version}`);
  }

  const lines = [
    '# Third-party licence texts (production dependencies)',
    '',
    '<!-- Generated by scripts/gen-third-party-licenses.mjs. Do not edit by hand. -->',
    '',
    'These are the licence notices of the packages that ship in the SPA or the',
    'Worker. They were read from each installed package by',
    '`node scripts/gen-third-party-licenses.mjs` after `pnpm install`; regenerate',
    'the file after any dependency change. Dev-only tooling is excluded from this',
    'file and from the deployed bundle.',
    '',
    `Packages: ${packages.length - missing.length}. Licence families: ${[...groups.keys()].sort().join(', ')}.`,
    '',
  ];

  for (const license of [...groups.keys()].sort()) {
    lines.push(`## ${license}`, '');
    const byText = groups.get(license);
    for (const [text, group] of byText) {
      lines.push(
        `### ${group.packages.length} package${group.packages.length === 1 ? '' : 's'} (${group.file})`,
        '',
        ...group.packages.sort().map((name) => `- \`${name}\``),
        '',
        '```text',
        text,
        '```',
        '',
      );
    }
  }

  if (missing.length > 0) {
    lines.push(
      '## Packages with no licence file in the installed package',
      '',
      'Flagged rather than guessed: verify each one before the next release.',
      '',
      ...missing.map((pkg) => `- \`${pkg.name}@${pkg.version}\` (declared ${pkg.license})`),
      '',
    );
  }

  writeFileSync(OUTPUT, `${lines.join('\n').trim()}\n`, 'utf8');
  console.log(
    `third-party licences: wrote ${path.relative(ROOT, OUTPUT)} — ` +
      `${packages.length - missing.length} packages, ${missing.length} without a licence file.`,
  );
  if (missing.length > 0) {
    for (const pkg of missing) console.warn(`  no licence file: ${pkg.name}@${pkg.version}`);
  }
}

main();
